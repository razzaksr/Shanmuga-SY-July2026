package day2;

public class SudokuValidation {
    public static boolean validate(char[][] grid){
        boolean[][] row = new boolean[9][9];
        boolean[][] col = new boolean[9][9];
        boolean[][] box = new boolean[9][9];
        for(int ind=0;ind<9;ind++){
            for(int j=0;j<9;j++){
                if(grid[ind][j]!='.'){
                    int num= grid[ind][j]-'1';
                    int bInd= (ind/3)*3+(j/3);
                    if(row[ind][num]||col[j][num]
                                    ||box[bInd][num]) 
                        return false;
                    row[ind] [ num ] = col[j][ num ]
                                 = box[bInd][ num ] = true;
                }
            }
        }
        return true;
    }
    public static void main(String[] args) {
        System.out.println(validate(new char[][]{
            {'5','3','.','.','7','.','.','.','.'},
            {'6','.','.','1','9','5','.','.','.'},
            {'.','9','8','.','.','.','.','6','.'},
            {'8','.','.','.','6','.','.','.','3'},
            {'4','.','.','8','.','3','.','.','1'},
            {'7','.','.','.','2','.','.','.','6'},
            {'.','6','.','.','.','.','2','8','.'},
            {'.','.','.','4','1','9','.','.','5'},
            {'.','.','.','.','8','.','.','7','9'}
        }));
        System.out.println(validate(new char[][]{
            {'8','3','.','.','7','.','.','.','.'},
            {'6','.','.','1','9','5','.','.','.'},
            {'.','9','8','.','.','.','.','6','.'},
            {'8','.','.','.','6','.','.','.','3'},
            {'4','.','.','8','.','3','.','.','1'},
            {'7','.','.','.','2','.','.','.','6'},
            {'.','6','.','.','.','.','2','8','.'},
            {'.','.','.','4','1','9','.','.','5'},
            {'.','.','.','.','8','.','.','7','9'}
        }));
    }
}
